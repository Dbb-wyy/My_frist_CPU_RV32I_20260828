.section .text
.globl _start

_start:
    # RAM base = 0x10000000
    lui  x10, 0x10000

    # =========================================================
    # SW / LW @ 0x10000000
    # =========================================================
    addi x1, x0, 0x55

    sw   x1, 0(x10)
    lw   x2, 0(x10)

    # =========================================================
    # SW / LW @ 0x10000004
    # =========================================================
    addi x1, x0, 0xaa

    sw   x1, 4(x10)
    lw   x3, 4(x10)

    # =========================================================
    # 修改 0x10000000
    # =========================================================
    sw   x1, 0(x10)
    lw   x4, 0(x10)

loop:
    jal x0, loop
