.section .text.init
.globl _start
.type _start, @function

_start:
    # ==========================================================
    # 1. 初始化栈指针
    # ==========================================================
    # _stack_top 由 linker.ld 定义，指向 RAM 的末尾。
    # RISC-V 栈向低地址增长，因此 sp 初始化为栈顶地址。
    la      sp, _stack_top

    # ==========================================================
    # 2. 将 .data 段从 ROM 拷贝到 RAM
    # ==========================================================
    # _data_lma   : .data 在 ROM 中的加载地址（源地址）
    # _data_start : .data 在 RAM 中的起始地址（目标地址）
    # _data_end   : .data 在 RAM 中的结束地址（不包含该地址）
    #
    # 每次复制 4 字节，因此源地址和目标地址都按 4 字节递增。
    # linker.ld 已对 .data 的首尾进行 4 字节对齐。
    la      a0, _data_lma
    la      a1, _data_start
    la      a2, _data_end

.Lcopy_data_loop:
    # 当目标地址达到结束地址时，复制完成。
    bgeu    a1, a2, .Lcopy_data_done

    # 从 ROM 读取一个字，写入 RAM。
    lw      t0, 0(a0)
    sw      t0, 0(a1)

    # 源地址和目标地址都移动 4 字节。
    addi    a0, a0, 4
    addi    a1, a1, 4
    j       .Lcopy_data_loop

.Lcopy_data_done:

    # ==========================================================
    # 3. 将 .bss 段清零
    # ==========================================================
    # .bss 保存未显式初始化或初始化为零的全局/静态变量。
    # 它在 RAM 中没有需要从 ROM 拷贝的初始数据，
    # 因此启动时将整个区间清零。
    #
    # _bss_start : .bss 起始地址
    # _bss_end   : .bss 结束地址（不包含该地址）
    #
    # linker.ld 已对 .bss 的首尾进行 4 字节对齐。
    la      a1, _bss_start
    la      a2, _bss_end

.Lclear_bss_loop:
    # 当目标地址达到结束地址时，清零完成。
    bgeu    a1, a2, .Lclear_bss_done

    # 写入一个 32 位的零。
    sw      x0, 0(a1)

    # 移动到下一个字。
    addi    a1, a1, 4
    j       .Lclear_bss_loop

.Lclear_bss_done:

    # ==========================================================
    # 4. 调用 C 语言入口 main
    # ==========================================================
    # 此时栈已设置，.data 已复制，.bss 已清零。
    # call 会保存返回地址到 ra，并跳转到 main。
    call    main

    # ==========================================================
    # 5. main 返回后的处理
    # ==========================================================
    # 将 main 的返回值 a0 保存到 x31，方便仿真时检查。
    # 这里沿用原有设计；x31 是通用寄存器，不是标准的
    # 专用退出状态寄存器。
    mv      x31, a0

.Lhalt:
    # 当前没有操作系统或其他运行时环境负责退出，
    # 因此 main 返回后停留在这里。
    j       .Lhalt

.size _start, . - _start