.section .text
.globl _start

_start:
    # =========================================================
    # LUI
    # =========================================================
    lui x1, 0x12345
    # 预期：
    # x1 = 0x12345000


    # =========================================================
    # AUIPC
    # =========================================================
    auipc x2, 0x1
    # auipc = 当前 PC + (0x1 << 12)
    #
    # 注意这里的“当前 PC”就是 AUIPC 这条指令自己的地址。
    #
    # 如果 auipc 位于 0x08：
    # x2 = 0x00001008
    #
    # 具体地址以你的实际程序布局为准。


loop:
    jal x0, loop
