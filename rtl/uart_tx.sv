`timescale 1ns / 1ps

//==============================================================================
// Module: uart_tx
// Description:
//   最基础的 UART 发送模块，采用 8N1 格式：
//     1 个起始位（低电平） + 8 个数据位（LSB first） + 1 个停止位（高电平）
//
//   缓冲结构：一个 TDR（发送数据寄存器）+ 一个发送移位寄存器，不包含 FIFO。
//
//   默认配置：
//     系统时钟：50 MHz
//     波特率：  115200 baud
//     每 bit 的时钟周期数：round(50,000,000 / 115,200) = 434
//
//   CPU / MMIO 接口由 top.sv 负责：
//     - 当 CPU 写 UART_TXDATA 地址时，top.sv 拉高 txdata_we 一个有效时钟沿；
//     - txdata[7:0] 是要发送的字节；
//     - top.sv 将 txe 和 tc 映射到 UART_STATUS 寄存器。
//
//   状态位语义：
//     txe = 1：TDR 为空，可以接受下一个字节。
//     tc  = 1：TDR 为空，并且当前没有正在发送的帧（发送完全结束）。
//
//   复位：rst 为高有效、同步复位，与本仓库 top.sv / CPU 的 rst 约定一致。
//==============================================================================
module uart_tx #(
    parameter integer CLK_FREQ_HZ = 50_000_000,
    parameter integer BAUD_RATE   = 115_200
) (
    input  logic       clk,        // 系统时钟
    input  logic       rst,        // 高有效同步复位

    // 来自 top.sv 的 MMIO 写接口。
    // txdata_we 应在写 UART_TXDATA 的那个有效时钟沿为高。
    input  logic       txdata_we,
    input  logic [7:0] txdata,

    // UART 状态位，建议映射为 UART_STATUS[0]=txe、UART_STATUS[1]=tc。
    output logic       txe,
    output logic       tc,

    // UART 串行发送输出。空闲时保持高电平。
    output logic       tx
);

    //-------------------------------------------------------------------------
    // 波特率分频参数
    //-------------------------------------------------------------------------
    // 用四舍五入计算一个 bit 对应的系统时钟周期数。
    // 50 MHz / 115200 baud -> 434 个时钟周期，实际波特率约 115207.4 baud。
    // 该误差很小，适合本项目第一版固定波特率 UART TX。
    localparam integer CLKS_PER_BIT =
        (CLK_FREQ_HZ + (BAUD_RATE / 2)) / BAUD_RATE;

    // 计数器位宽至少为 1，避免参数较小时出现零位宽向量。
    localparam integer BAUD_CNT_WIDTH =
        (CLKS_PER_BIT <= 1) ? 1 : $clog2(CLKS_PER_BIT);

    //-------------------------------------------------------------------------
    // 发送状态机状态定义
    //-------------------------------------------------------------------------
    localparam logic [1:0] ST_IDLE  = 2'd0; // 空闲，等待 TDR 中出现数据
    localparam logic [1:0] ST_START = 2'd1; // 正在发送起始位
    localparam logic [1:0] ST_DATA  = 2'd2; // 正在发送 8 个数据位
    localparam logic [1:0] ST_STOP  = 2'd3; // 正在发送停止位

    logic [1:0] state;

    //-------------------------------------------------------------------------
    // TDR：发送数据寄存器（1 字节缓冲）
    //-------------------------------------------------------------------------
    logic [7:0] tdr;
    logic       tdr_full; // 1 表示 TDR 中存有尚未转移到移位寄存器的数据

    //-------------------------------------------------------------------------
    // 发送移位寄存器及计数器
    //-------------------------------------------------------------------------
    logic [7:0] shift_reg;                    // 当前正在串行发送的字节
    logic [2:0] bit_index;                    // 当前数据位编号：0 到 7
    logic [BAUD_CNT_WIDTH-1:0] baud_cnt;      // 当前 bit 的时钟周期计数器

    //-------------------------------------------------------------------------
    // 状态输出
    //-------------------------------------------------------------------------
    // TXE 只由 TDR 是否为空决定；数据一旦转入移位寄存器，TXE 就可以置 1，
    // 即使前一个字节还在串行发送，软件也可以把下一个字节放入 TDR。
    assign txe = ~tdr_full;

    // TC 需要同时满足两个条件：TDR 为空、发送状态机处于完全空闲状态。
    // 因此，最后一个停止位发送完毕后 TC 才会变为 1。
    assign tc = (~tdr_full) && (state == ST_IDLE);

    //-------------------------------------------------------------------------
    // 主时序逻辑：TDR 管理 + UART 发送状态机
    //-------------------------------------------------------------------------
    always_ff @(posedge clk) begin
        if (rst) begin
            // 同步复位：UART 线路空闲为高电平，TDR 和状态机清空。
            state     <= ST_IDLE;
            tdr       <= 8'h00;
            tdr_full  <= 1'b0;
            shift_reg <= 8'h00;
            bit_index <= 3'd0;
            baud_cnt  <= '0;
            tx        <= 1'b1;
        end else begin

            //-----------------------------------------------------------------
            // 1. CPU 写 TDR
            //-----------------------------------------------------------------
            // 仅当 TDR 原本为空时才接受写入。
            // 若软件未轮询 TXE、在 TDR 已满时继续写，新的字节会被忽略，
            // 不会覆盖原来尚未发送的数据。软件应先等待 TXE=1 再写入。
            //
            // 注意：这里判断的是时钟沿之前的 tdr_full 状态。因此在 TDR 恰好
            // 转移到移位寄存器的那个时钟沿，如果 txdata_we 也为 1，写入仍会被
            // 拒绝；软件看到 TXE 变为 1 后，在后续时钟沿写入即可。
            if (txdata_we && !tdr_full) begin
                tdr      <= txdata;
                tdr_full <= 1'b1;
            end

            //-----------------------------------------------------------------
            // 2. UART TX 发送状态机
            //-----------------------------------------------------------------
            case (state)

                //-------------------------------------------------------------
                // IDLE：TX 保持高电平，等待 TDR 中有有效数据。
                //-------------------------------------------------------------
                ST_IDLE: begin
                    tx       <= 1'b1;
                    baud_cnt <= '0;
                    bit_index <= 3'd0;

                    if (tdr_full) begin
                        // 将 TDR 中的字节复制到移位寄存器，并释放 TDR。
                        // 经过这个时钟沿后，txe 会变为 1，软件可写入下一个字节。
                        shift_reg <= tdr;
                        tdr_full  <= 1'b0;

                        // 起始位为低电平，并从此刻开始计满 CLKS_PER_BIT 个时钟。
                        tx       <= 1'b0;
                        baud_cnt <= '0;
                        state    <= ST_START;
                    end
                end

                //-------------------------------------------------------------
                // START：维持起始位低电平整整一个 bit 周期。
                //-------------------------------------------------------------
                ST_START: begin
                    if (baud_cnt == CLKS_PER_BIT - 1) begin
                        // 起始位结束，开始发送 bit 0（最低有效位）。
                        baud_cnt  <= '0;
                        bit_index <= 3'd0;
                        tx        <= shift_reg[0];
                        state     <= ST_DATA;
                    end else begin
                        baud_cnt <= baud_cnt + 1'b1;
                    end
                end

                //-------------------------------------------------------------
                // DATA：LSB first，依次发送 shift_reg[0] 到 shift_reg[7]。
                //-------------------------------------------------------------
                ST_DATA: begin
                    if (baud_cnt == CLKS_PER_BIT - 1) begin
                        // 当前数据位的周期已经结束。
                        baud_cnt <= '0;

                        if (bit_index == 3'd7) begin
                            // bit 7 发送完毕，进入停止位。
                            // 停止位为高电平。
                            tx    <= 1'b1;
                            state <= ST_STOP;
                        end else begin
                            // 右移一位，让下一位数据来到 bit 0。
                            // 非阻塞赋值使 tx 取到移位前的 shift_reg[1]，
                            // 正好是下一个需要发送的数据位。
                            shift_reg <= {1'b0, shift_reg[7:1]};
                            bit_index <= bit_index + 1'b1;
                            tx        <= shift_reg[1];
                        end
                    end else begin
                        baud_cnt <= baud_cnt + 1'b1;
                    end
                end

                //-------------------------------------------------------------
                // STOP：维持停止位高电平整整一个 bit 周期。
                //-------------------------------------------------------------
                ST_STOP: begin
                    tx <= 1'b1;

                    if (baud_cnt == CLKS_PER_BIT - 1) begin
                        // 整个帧（起始位 + 8 数据位 + 停止位）已经发送完成。
                        baud_cnt <= '0;
                        state    <= ST_IDLE;
                        // 若 TDR 已经装入下一个字节，下一拍在 IDLE 中启动它。
                        // 此时 TC 仍为 0；只有 TDR 为空时 TC 才会变为 1。
                    end else begin
                        baud_cnt <= baud_cnt + 1'b1;
                    end
                end

                //-------------------------------------------------------------
                // 防御性默认分支：状态异常时回到空闲状态。
                //-------------------------------------------------------------
                default: begin
                    state     <= ST_IDLE;
                    tdr_full  <= 1'b0;
                    baud_cnt  <= '0;
                    bit_index <= 3'd0;
                    tx        <= 1'b1;
                end

            endcase
        end
    end

endmodule
